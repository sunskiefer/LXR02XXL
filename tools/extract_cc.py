#!/usr/bin/env python3
"""Cut the LXR firmware's parameter handler and the menu's parameter tables out of the vendored firmware, verbatim.

    python3 tools/extract_cc.py   -> src/lxr/cc_handler.inc, src/lxr/menu_tables.inc

midiParser_ccHandler() in Core/Src/Soundengine/MIDI/MidiParser.c (Erica Synths LXR firmware, GPL-3.0) is where every
sound parameter (0-127 as a CC, 128+ as the firmware's second CC page) becomes DSP state. LXRXXL compiles exactly that
code; the rest of the file (UART/USB parsing, MTC, routing) belongs to the hardware. The cut runs from
calcPitchModAmount() to the end of the handler. From Core/Src/menu/menu.c it takes the parameter value types
(parameter_dtypes) and the parameter names (valueNames), used for the screen's value text.
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FW = os.path.join(ROOT, "third_party", "lxr-desktop-app", "Core", "Src")
rel = lambda p: os.path.relpath(p, ROOT)

mp = os.path.join(FW, "Soundengine", "MIDI", "MidiParser.c")
src = open(mp, encoding="latin-1").read().split("\n")
start = next(i for i, l in enumerate(src) if l.startswith("static inline float calcPitchModAmount"))
start -= 1   # its comment line
end = next(i for i, l in enumerate(src) if l.startswith("void midiParser_checkMtc()"))
while not src[end - 1].startswith("}"):
    end -= 1
# the parser's own state (serial parsing) is not part of the handler; lxr_dsp.c defines what the handler uses
skip = ("MidiMsg midiMsg_tmp;", "static uint8_t parserState")
out = ["/* LXRXXL: not needed here -- " + l.strip() + " */" if l.startswith(skip) else l for l in src[start:end]]
hdr = ["/* GENERATED by tools/extract_cc.py from %s (lines %d-%d): do not edit." % (rel(mp), start + 1, end),
       " * The LXR firmware's parameter handler, verbatim. Copyright (C) 2012-2026 Erica Synths, GPL-3.0-only",
       " * (third_party/lxr-desktop-app/LICENSE, NOTICE.md). */"]
open(os.path.join(ROOT, "src", "lxr", "cc_handler.inc"), "w").write("\n".join(hdr + out) + "\n")
print("cc_handler.inc: lines %d-%d" % (start + 1, end))

mc = os.path.join(FW, "menu", "menu.c")
menu = open(mc, encoding="latin-1").read().split("\n")
def cut(first_prefix):
    s = next(i for i, l in enumerate(menu) if l.startswith(first_prefix))
    e = next(i for i in range(s, len(menu)) if menu[i].startswith("};"))
    return menu[s:e + 1], s + 1, e + 1
dt, a, b = cut("const enum Datatypes PROGMEM parameter_dtypes[NUM_PARAMS]")
vn, c, d = cut("const Name valueNames[NUM_NAMES]")
open(os.path.join(ROOT, "src", "lxr", "menu_tables.inc"), "w").write("\n".join(
    ["/* GENERATED by tools/extract_cc.py from %s (lines %d-%d, %d-%d): do not edit." % (rel(mc), a, b, c, d),
     " * Copyright (C) 2012-2026 Erica Synths, GPL-3.0-only. */"]
    + dt + [""] + vn) + "\n")
print("menu_tables.inc: lines %d-%d, %d-%d" % (a, b, c, d))
